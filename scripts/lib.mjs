export function randomSecret(bytes = 32) {
  return randomBytes(bytes).toString('base64url');
}

/** An RS256 private JWK with a kid, in the format of OIDC_SIGNING_KEYS (apps/idp/src/signing-keys.ts). */
export function generateSigningJwk() {
  const { privateKey } = generateKeyPairSync('rsa', { modulusLength: 2048, publicExponent: 0x10001 });
  const jwk = privateKey.export({ format: 'jwk' });
  const kid = `idp-${new Date().toISOString().slice(0, 10)}-${randomBytes(4).toString('hex')}`;
  return { kty: 'RSA', kid, n: jwk.n, e: jwk.e, d: jwk.d, p: jwk.p, q: jwk.q, dp: jwk.dp, dq: jwk.dq, qi: jwk.qi };
}

/** The relying party entry of OIDC_CLIENTS_JSON (apps/idp/src/clients.ts) for the planner. */
export function plannerClient(plannerOrigin, clientSecret) {
  return {
    clientId: CLIENT_ID,
    clientSecret,
    clientType: 'confidential',
    redirectUris: [`${plannerOrigin}/auth/callback`],
    postLogoutRedirectUris: [`${plannerOrigin}/signed-out`],
    grantTypes: ['authorization_code'],
    responseTypes: ['code'],
    tokenEndpointAuthMethods: ['client_secret_basic'],
    scope: ['openid', 'profile', 'email'],
  };
}

/**
 * The hash the planner keeps for the routine's bearer token
 * (ROUTINE_BEARER_TOKEN_HASH): base64url SHA-256, as hashBearerToken() of
 * apps/planner/src/auth/routine-token.ts makes it.
 */
export function hashSecret(secret) {
  return createHash('sha256').update(secret, 'utf8').digest('base64url');
}

/** Reads KEY=value lines (single-quoted values allowed) of a .dev.vars file. */
export function readDevVars(file) {
  if (!existsSync(file)) return {};
  const vars = {};
  for (const line of readFileSync(file, 'utf8').split('\n')) {
    const match = /^([A-Z0-9_]+)=(.*)$/.exec(line.trim());
    if (!match) continue;
    let value = match[2];
    if (value.startsWith("'") && value.endsWith("'")) value = value.slice(1, -1);
    else if (value.startsWith('"') && value.endsWith('"')) value = JSON.parse(value);
    vars[match[1]] = value;
  }
  return vars;
}

export function writeDevVars(file, vars) {
  const lines = ['# Generated by `pnpm setup:local`. Local development only; never commit this file.'];
  for (const [key, value] of Object.entries(vars)) {
    if (value === undefined) continue;
    if (String(value).includes("'")) throw new Error(`${key} contains a single quote`);
    lines.push(`${key}='${value}'`);
  }
  writeFileSync(file, `${lines.join('\n')}\n`, { mode: 0o600 });
}

/** Runs a command and returns its stdout; throws with its output when it fails. */
export function run(command, args, options = {}) {
  const result = spawnSync(command, args, {
    cwd: options.cwd ?? ROOT,
    encoding: 'utf8',
    input: options.input,
    env: { ...process.env, ...(options.env ?? {}) },
    stdio: [options.input === undefined ? 'inherit' : 'pipe', 'pipe', 'pipe'],
  });
  if (result.status !== 0 && !options.allowFailure) {
    const output = `${result.stdout ?? ''}${result.stderr ?? ''}`.trim();
    throw new Error(`${command} ${args.join(' ')} failed (exit ${result.status}):\n${output}`);
  }
  return { status: result.status, stdout: result.stdout ?? '', stderr: result.stderr ?? '' };
}

/** Runs wrangler of an app (its own devDependency) and returns stdout. */
export function wrangler(appDir, args, options = {}) {
  return run('pnpm', ['exec', 'wrangler', ...args], { ...options, cwd: appDir });
}

/** Runs a command with its output streamed to the terminal (for long steps such as deploy). */
export function runStreaming(command, args, options = {}) {
  return new Promise((resolvePromise, reject) => {
    const child = spawn(command, args, { cwd: options.cwd ?? ROOT, stdio: ['inherit', 'pipe', 'pipe'], env: process.env });
    let output = '';
    child.stdout.on('data', (chunk) => {
      output += chunk;
      process.stdout.write(chunk);
    });
    child.stderr.on('data', (chunk) => {
      output += chunk;
      process.stderr.write(chunk);
    });
    child.on('close', (code) => (code === 0 ? resolvePromise(output) : reject(new Error(`${command} ${args.join(' ')} failed (exit ${code})`))));
  });
}

let rl;
export async function ask(question, { defaultValue, secret = false } = {}) {
  if (!process.stdin.isTTY) {
    if (defaultValue !== undefined) return defaultValue;
    throw new Error(`入力が必要です（非対話環境）: ${question}`);
  }
  const suffix = defaultValue ? ` [${secret ? '設定済み' : defaultValue}]` : '';
  if (secret) {
    const answer = await askHidden(`${question}${suffix}: `);
    return answer.trim() || defaultValue || '';
  }
  rl ??= createInterface({ input: process.stdin, output: process.stdout, terminal: true });
  const answer = await rl.question(`${question}${suffix}: `);
  return answer.trim() || defaultValue || '';
}

/**
 * Reads one line from the terminal without showing it. The terminal is put
 * in raw mode and the characters are collected here, so nothing is echoed
 * (readline would print them itself). Backspace and Ctrl+U edit, Ctrl+C aborts.
 */
export function askHidden(prompt) {
  // The shared readline interface listens on stdin too; it is created again by the next ask().
  closePrompts();
  const stdin = process.stdin;
  process.stdout.write(prompt);
  stdin.setRawMode(true);
  stdin.setEncoding('utf8');
  stdin.resume();
  return new Promise((resolvePromise) => {
    let value = '';
    const finish = () => {
      stdin.off('data', onData);
      stdin.setRawMode(false);
      stdin.pause();
      process.stdout.write('\n');
    };
    const onData = (chunk) => {
      // Drop escape sequences such as arrow keys and bracketed-paste markers.
      for (const char of chunk.replace(/\x1b\[[0-9;]*[~A-Za-z]/g, '')) {
        if (char === '\r' || char === '\n') {
          finish();
          resolvePromise(value);
          return;
        }
        if (char === '\u0003') {
          finish();
          process.exit(130);
        }
        if (char === '\u007f' || char === '\b') value = value.slice(0, -1);
        else if (char === '\u0015') value = '';
        else if (char >= ' ') value += char;
      }
    };
    stdin.on('data', onData);
  });
}

export async function confirm(question, defaultYes = false) {
  const answer = (await ask(`${question} (${defaultYes ? 'Y/n' : 'y/N'})`, { defaultValue: defaultYes ? 'y' : 'n' })).toLowerCase();
  return answer === 'y' || answer === 'yes';
}

export function closePrompts() {
  rl?.close();
  rl = undefined;
}
